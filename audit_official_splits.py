
import pandas as pd
from datasets import load_dataset
from pathlib import Path

# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

OUTPUT_DIR = Path("outputs")
OUTPUT_DIR.mkdir(exist_ok=True)

DATASET = "yaful/MAGE"

# The ten domains named in the official MAGE repository,
# plus four additional domains used in its wilder test set.
DOMAINS = [
    "cmv", "yelp", "xsum", "tldr", "eli5",
    "wp", "roct", "hswag", "squad", "sci_gen",
    "cnn", "dialogsum", "imdb", "pubmed"
]

# Match longer domain names first, especially sci_gen.
DOMAINS = sorted(DOMAINS, key=len, reverse=True)

# Generator identifiers listed in the official MAGE
# testbed preparation code.
MODEL_PATTERNS = [
    "gpt-3.5-trubo",
    "text-davinci-003",
    "text-davinci-002",
    "glm130b",
    "flan_t5_small",
    "flan_t5_base",
    "flan_t5_large",
    "flan_t5_xl",
    "flan_t5_xxl",
    "opt_iml_max_1.3b",
    "opt_iml_30b",
    "opt_125m",
    "opt_350m",
    "opt_1.3b",
    "opt_2.7b",
    "opt_6.7b",
    "opt_13b",
    "opt_30b",
    "bloom_7b",
    "t0_3b",
    "t0_11b",
    "gpt_j",
    "gpt_neox",
    "_7b",
    "_13b",
    "_30b",
    "_65b",
]

MODEL_PATTERNS = sorted(
    MODEL_PATTERNS,
    key=len,
    reverse=True
)


# --------------------------------------------------
# 2. Helper functions
# --------------------------------------------------

def extract_domain(src):

    src = str(src).lower()

    for domain in DOMAINS:
        if src == domain or src.startswith(domain + "_"):
            return domain

    return "unknown"


def classify_source(src):

    src = str(src).lower()

    if "_machine_" in src:
        return "machine_generated"

    # MAGE documents these as paraphrases of human
    # source text generated by an LLM.
    if src.endswith("_human_para"):
        return "machine_paraphrase"

    if src.endswith("_human"):
        return "human_original"

    return "other_or_unknown"


def extract_generator(src):

    src = str(src).lower()

    if "_machine_" not in src:
        return None, None

    tail = src.split("_machine_", 1)[1]

    for pattern in MODEL_PATTERNS:

        if pattern in tail:
            position = tail.find(pattern)

            method = tail[:position].strip("_")

            return pattern, method if method else "unknown"

    return "unmapped", "unmapped"


# --------------------------------------------------
# 3. Load all available dataset splits
# --------------------------------------------------

print("=" * 65)
print("MAGE OFFICIAL SPLIT AUDIT")
print("=" * 65)

print("\nLoading MAGE dataset and available splits...")

dataset_dict = load_dataset(DATASET)

print("\nAVAILABLE SPLITS")
print(list(dataset_dict.keys()))


# --------------------------------------------------
# 4. Inspect each split
# --------------------------------------------------

all_metadata = []
split_summary = []
domain_summary = []
source_summary = []
generator_summary = []

for split_name, dataset in dataset_dict.items():

    print("\n" + "-" * 65)
    print(f"INSPECTING SPLIT: {split_name}")
    print("-" * 65)

    available_columns = dataset.column_names

    if "label" not in available_columns:
        print("No label column found. Skipping this split.")
        continue

    columns_to_keep = [
        column for column in ["label", "src"]
        if column in available_columns
    ]

    metadata = dataset.select_columns(
        columns_to_keep
    ).to_pandas()

    if "src" not in metadata.columns:
        metadata["src"] = "source_not_provided"

    metadata["split_name"] = split_name

    metadata["label"] = pd.to_numeric(
        metadata["label"], errors="coerce"
    )

    metadata["src"] = metadata["src"].fillna(
        "source_not_provided"
    ).astype(str)

    metadata["domain"] = metadata["src"].apply(
        extract_domain
    )

    metadata["source_type"] = metadata["src"].apply(
        classify_source
    )

    parsed = metadata["src"].apply(
        lambda src: extract_generator(src)
    )

    metadata["generator_model"] = parsed.apply(
        lambda x: x[0]
    )

    metadata["generation_method"] = parsed.apply(
        lambda x: x[1]
    )

    # Keep label counts based on actual dataset labels.
    print("\nRECORD COUNT:", len(metadata))

    print("\nLABEL COUNTS")
    print(
        metadata["label"]
        .value_counts(dropna=False)
        .sort_index()
        .to_string()
    )

    print("\nDISTINCT SOURCE CATEGORIES")
    print(metadata["src"].nunique())

    print("\nCANDIDATE DOMAIN COUNTS")
    print(
        metadata["domain"]
        .value_counts()
        .to_string()
    )

    # Overall split statistics.
    label_counts = metadata["label"].value_counts()

    split_summary.append({
        "split": split_name,
        "records": len(metadata),
        "label_0_AI": int(label_counts.get(0, 0)),
        "label_1_human": int(label_counts.get(1, 0)),
        "distinct_sources": metadata["src"].nunique(),
        "distinct_domains": metadata["domain"].nunique(),
        "unknown_domain_records": int(
            (metadata["domain"] == "unknown").sum()
        ),
    })

    # Domain by label.
    domain_table = pd.crosstab(
        [
            metadata["split_name"],
            metadata["domain"]
        ],
        metadata["label"]
    ).reset_index()

    domain_summary.append(domain_table)

    # Source by label.
    source_table = pd.crosstab(
        [
            metadata["split_name"],
            metadata["src"]
        ],
        metadata["label"]
    ).reset_index()

    source_summary.append(source_table)

    # Generator inventory.
    machine = metadata[
        (metadata["label"] == 0)
        & metadata["generator_model"].notna()
    ]

    if not machine.empty:

        generator_table = (
            machine.groupby([
                "split_name",
                "domain",
                "generator_model",
                "generation_method"
            ])
            .size()
            .reset_index(name="records")
        )

        generator_summary.append(generator_table)

    # Check source categories containing both labels.
    source_label_variety = (
        metadata.groupby("src")["label"].nunique()
    )

    both_labels = int(
        (source_label_variety > 1).sum()
    )

    print(
        "\nSources containing both labels:",
        both_labels
    )

    all_metadata.append(metadata)


# --------------------------------------------------
# 5. Combine and save all audit results
# --------------------------------------------------

if not all_metadata:
    raise RuntimeError("No dataset metadata was retrieved.")

combined = pd.concat(
    all_metadata,
    ignore_index=True
)

split_summary_df = pd.DataFrame(split_summary)

domain_summary_df = pd.concat(
    domain_summary,
    ignore_index=True
)

source_summary_df = pd.concat(
    source_summary,
    ignore_index=True
)

generator_summary_df = (
    pd.concat(generator_summary, ignore_index=True)
    if generator_summary
    else pd.DataFrame()
)

split_summary_df.to_csv(
    OUTPUT_DIR / "official_split_summary.csv",
    index=False
)

domain_summary_df.to_csv(
    OUTPUT_DIR / "official_domain_label_counts.csv",
    index=False
)

source_summary_df.to_csv(
    OUTPUT_DIR / "official_source_label_counts.csv",
    index=False
)

generator_summary_df.to_csv(
    OUTPUT_DIR / "official_generator_inventory.csv",
    index=False
)

combined.to_csv(
    OUTPUT_DIR / "official_all_split_metadata.csv",
    index=False
)


# --------------------------------------------------
# 6. Focus on our three experimental domains
# --------------------------------------------------

selected_domains = combined[
    combined["domain"].isin(["yelp", "squad", "eli5"])
].copy()

selected_summary = pd.crosstab(
    [
        selected_domains["split_name"],
        selected_domains["domain"]
    ],
    selected_domains["label"]
).reset_index()

selected_summary.to_csv(
    OUTPUT_DIR / "selected_domain_split_counts.csv",
    index=False
)

print("\n" + "=" * 65)
print("OFFICIAL SPLIT SUMMARY")
print("=" * 65)

print(split_summary_df.to_string(index=False))

print("\n" + "=" * 65)
print("YELP, SQUAD AND ELI5 COUNTS BY SPLIT")
print("=" * 65)

print(selected_summary.to_string(index=False))

print("\n" + "=" * 65)
print("GENERATOR INVENTORY FOR SELECTED DOMAINS")
print("=" * 65)

if not generator_summary_df.empty:

    selected_generators = generator_summary_df[
        generator_summary_df["domain"].isin(
            ["yelp", "squad", "eli5"]
        )
    ]

    print(
        selected_generators.sort_values(
            ["split_name", "domain", "records"],
            ascending=[True, True, False]
        ).to_string(index=False)
    )

print("\nAUDIT COMPLETED SUCCESSFULLY.")

print("\nFILES SAVED:")
print("official_split_summary.csv")
print("official_domain_label_counts.csv")
print("official_source_label_counts.csv")
print("official_generator_inventory.csv")
print("selected_domain_split_counts.csv")
print("official_all_split_metadata.csv")

print("\nOutput folder:", OUTPUT_DIR.resolve())
